export type ProjectCategory = 'Web' | 'Android' | 'ML/AI' | 'Other';

export const SKILL_CATEGORIES = ['Languages', 'Web', 'Backend/DB', 'Mobile', 'DevOps/Cloud'] as const;
export type SkillCategory = (typeof SKILL_CATEGORIES)[number];

export interface Project {
  id: string;
  name: string;
  slug: string;
  description: string;
  longDescription?: string;
  problem?: string;
  solution?: string;
  duration?: string;
  startDate?: string | null;
  endDate?: string | null;
  category: ProjectCategory;
  skills: string[];
  github?: string;
  liveUrl?: string;
  images: string[];
  featured: boolean;
  published: boolean;
  order: number;
}

export interface Stat {
  id: string;
  label: string;
  value: number;
  suffix?: string;
  decimals?: number;
  platform?: string;
  url?: string;
  order: number;
}

export interface Experience {
  id: string;
  role: string;
  org: string;
  type?: 'internship' | 'work' | 'leadership';
  start: string;
  end?: string | null;
  current?: boolean;
  description?: string;
  highlights: string[];
  featured?: boolean;
  order: number;
}

export interface Profile {
  fullName: string;
  tagline?: string;
  githubBio?: string;
  bio?: string;
  roles?: string[];
  emails: string[];
  links: { linkedin?: string; github?: string; instagram?: string; facebook?: string };
  resumeUrl?: string;
  dob?: string; // only present when the admin has enabled "show date of birth"
}

export interface Skill {
  id: string;
  name: string;
  category: SkillCategory;
  featured: boolean;
  level?: number; // 0 = not displayed
  order: number;
}

export interface Certification {
  id: string;
  title: string;
  issuer?: string;
  url?: string;
  date?: string;
  featured?: boolean;
  order: number;
}

export interface Achievement {
  id: string;
  text: string;
  featured?: boolean;
  order: number;
}

export interface Semester {
  sem: number;
  sgpa: number;
}

export interface Qualification {
  id: string;
  level: string;
  institution: string;
  score?: string;
  semesters?: Semester[];
  year?: string;
  order: number;
}

// Shape of src/data/fallback.json (generated by `npm run export:fallback` in /server).
export interface FallbackData {
  profile: Profile;
  stats: Stat[];
  projects: Project[];
  experience: Experience[];
  qualifications: Qualification[];
  achievements: Achievement[];
  certifications: Certification[];
  skills: Skill[];
}