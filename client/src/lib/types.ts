export type ProjectCategory = 'Web' | 'Android' | 'ML/AI' | 'Other';

export interface Project {
  id: string;
  name: string;
  slug: string;
  description: string;
  longDescription?: string;
  problem?: string;
  solution?: string;
  duration?: string;
  startDate?: string | null;
  endDate?: string | null;
  category: ProjectCategory;
  skills: string[];
  github?: string;
  liveUrl?: string;
  images: string[];
  featured: boolean;
  published: boolean;
  order: number;
}

export interface Stat {
  id: string;
  label: string;
  value: number;
  suffix?: string;
  decimals?: number;
  platform?: string;
  url?: string;
  order: number;
}

export interface Experience {
  id: string;
  role: string;
  org: string;
  type?: 'internship' | 'work' | 'leadership';
  start: string;
  end?: string | null;
  current?: boolean;
  description?: string;
  highlights: string[];
  featured?: boolean;
  order: number;
}

export interface Profile {
  fullName: string;
  tagline?: string;
  githubBio?: string;
  bio?: string;
  roles?: string[];
  emails: string[];
  links: { linkedin?: string; github?: string; instagram?: string; facebook?: string };
  resumeUrl?: string;
  dob?: string;
}

// Shape of src/data/fallback.json (generated by `npm run export:fallback` in /server).
// Phase 4 adds typed access to the remaining collections.
export interface FallbackData {
  profile: Profile;
  stats: Stat[];
  projects: Project[];
  experience: Experience[];
}